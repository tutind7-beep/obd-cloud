"""База знаний и правила диагностики OBD-II.

Код ошибки + текущие параметры -> список подсказок с приоритетом.
Работает офлайн, без моделей и интернета.
"""

from __future__ import annotations

from dataclasses import dataclass, field

# Порядок вывода: сначала самое важное
SEVERITY_ORDER = {"СТОП": 0, "СКОРО В СЕРВИС": 1, "НАБЛЮДАТЬ": 2}


@dataclass
class Hint:
    """Одна подсказка: насколько срочно, что случилось и что делать."""

    severity: str
    title: str
    actions: list[str] = field(default_factory=list)

    def to_dict(self) -> dict:
        return {
            "severity": self.severity,
            "title": self.title,
            "actions": self.actions,
        }


