def find_rule(code: str) -> Hint | None:
    """Ищет правило для кода: сначала точное, потом по серии P030x."""
    if code in DTC_RULES:
        rule = DTC_RULES[code]
        return Hint(rule["severity"], f"{rule['title']} ({code})", list(rule["actions"]))

    # P0301..P0308 — пропуски в конкретном цилиндре
    if code.startswith("P030") and code[-1] in "12345678":
        cylinder = code[-1]
        return Hint(
            "СКОРО В СЕРВИС",
            f"Пропуски зажигания в цилиндре {cylinder} ({code})",
            [
                f"Поменяй местами катушку и свечу цилиндра {cylinder} с соседним: "
                "если ошибка перейдёт — виновата деталь.",
                "Проверь компрессию в этом цилиндре.",
                "Проверь форсунку.",
            ],
        )

    for prefix, severity, title, actions in PREFIX_RULES:
        if code.startswith(prefix):
            return Hint(severity, f"{title} ({code})", list(actions))

    return None


def check_live_data(live: dict) -> list[Hint]:
    """Проверяет текущие параметры по простым порогам."""
    hints = []

    coolant = live.get("coolant")
    if coolant is not None and coolant > 105:
        hints.append(
            Hint(
                "СТОП",
                "Перегрев двигателя",
                [
                    "Остановись в безопасном месте и заглуши двигатель.",
                    "Не открывай крышку расширительного бачка на горячем двигателе.",
                    "Проверь уровень антифриза, вентилятор и термостат после остывания.",
                ],
            )
        )

    trims = [
        value
        for value in (live.get("fuel_trim_short"), live.get("fuel_trim_long"))
        if value is not None
    ]
    if trims:
        worst_trim = max(trims, key=abs)
        if worst_trim > 10:
            severity = "СКОРО В СЕРВИС" if worst_trim > 15 else "НАБЛЮДАТЬ"
            hints.append(
                Hint(
                    severity,
                    f"Топливная коррекция +{worst_trim:.1f} %: смесь бедная",
                    [
                        "Проверь подсос воздуха: патрубки, шланги, прокладки впуска.",
                        "Проверь датчик MAF и давление топлива.",
                    ],
                )
            )
        elif worst_trim < -10:
            severity = "СКОРО В СЕРВИС" if worst_trim < -15 else "НАБЛЮДАТЬ"
            hints.append(
                Hint(
                    severity,
                    f"Топливная коррекция {worst_trim:.1f} %: смесь богатая",
                    [
                        "Проверь форсунки на подтекание.",
                        "Проверь датчик MAF и регулятор давления топлива.",
                    ],
                )
            )

    voltage = live.get("voltage")
    rpm = live.get("rpm")
    if voltage is not None:
        if rpm is not None and rpm > 500 and voltage < 13.0:
            hints.append(
                Hint(
                    "СКОРО В СЕРВИС",
                    f"Низкое напряжение при работающем двигателе: {voltage:.1f} В",
                    [
                        "Проверь ремень генератора и клеммы аккумулятора.",
                        "Проверь генератор: при работающем двигателе должно быть 13.5–14.5 В.",
                    ],
                )
            )
        elif (rpm is None or rpm < 500) and voltage < 11.8:
            hints.append(
                Hint(
                    "НАБЛЮДАТЬ",
                    f"Разряжен аккумулятор: {voltage:.1f} В",
                    [
                        "Поставь аккумулятор на зарядку.",
                        "Если повторяется — проверь генератор и утечки тока.",
                    ],
                )
            )

    return hints


def normalize_codes(codes: list[str]) -> list[str]:
    """Приводит коды к виду P0171: без пробелов и в верхнем регистре."""
    return [code.strip().upper() for code in codes if code and code.strip()]


def build_hints(codes: list[str], live: dict) -> list[Hint]:
    """Собирает все подсказки и сортирует по срочности."""
    hints = []

    for code in codes:
        rule = find_rule(code)
        if rule is not None:
            hints.append(rule)

    hints.extend(check_live_data(live))
    hints.sort(key=lambda hint: SEVERITY_ORDER[hint.severity])
    return hints
